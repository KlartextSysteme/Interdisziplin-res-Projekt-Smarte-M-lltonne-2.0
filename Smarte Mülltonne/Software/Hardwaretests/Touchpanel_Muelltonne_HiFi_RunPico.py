class ILI9341:
    def __init__(self):
        self.spi = SPI(
            SPI_ID,
            baudrate=SPI_BAUDRATE,
            polarity=0,
            phase=0,
            sck=Pin(PIN_SCK),
            mosi=Pin(PIN_MOSI),
        )
        self.cs = Pin(PIN_DISPLAY_CS, Pin.OUT, value=1)
        self.dc = Pin(PIN_DISPLAY_DC, Pin.OUT, value=1)
        self.rst = Pin(PIN_DISPLAY_RST, Pin.OUT, value=1)
        self.width = WIDTH
        self.height = HEIGHT

    def cmd(self, value):
        self.cs.off()
        self.dc.off()
        self.spi.write(bytearray([value]))
        self.cs.on()

    def data(self, values):
        self.cs.off()
        self.dc.on()
        self.spi.write(bytearray(values))
        self.cs.on()

    def reset(self):
        self.rst.on()
        sleep_ms(50)
        self.rst.off()
        sleep_ms(100)
        self.rst.on()
        sleep_ms(150)

    def init(self):
        self.reset()
        self.cmd(0x01)
        sleep_ms(120)
        self.cmd(0x11)
        sleep_ms(120)
        self.cmd(0x3A)
        self.data([0x55])
        self.cmd(0x36)
        self.data([DISPLAY_ROTATION])
        self.cmd(0x29)
        sleep_ms(50)

    def set_window(self, x0, y0, x1, y1):
        self.cmd(0x2A)
        self.data([x0 >> 8, x0 & 255, x1 >> 8, x1 & 255])
        self.cmd(0x2B)
        self.data([y0 >> 8, y0 & 255, y1 >> 8, y1 & 255])
        self.cmd(0x2C)

    def fill_rect(self, x, y, w, h, color):
        if w <= 0 or h <= 0:
            return
        x = max(0, min(self.width - 1, x))
        y = max(0, min(self.height - 1, y))
        w = min(w, self.width - x)
        h = min(h, self.height - y)
        self.set_window(x, y, x + w - 1, y + h - 1)
        hi = color >> 8
        lo = color & 255
        line = bytearray([hi, lo] * w)
        self.cs.off()
        self.dc.on()
        for _ in range(h):
            self.spi.write(line)
        self.cs.on()

    def fill_screen(self, color):
        self.fill_rect(0, 0, self.width, self.height, color)


def draw_bin_icon(display, x=None, y=1):
    if x is None:
        x = (display.width - ICON_W) // 2

    display.fill_screen(WHITE)
    display.set_window(x, y, x + ICON_W - 1, y + ICON_H - 1)

    line = bytearray(ICON_W * 2)
    pos = 0
    display.cs.off()
    display.dc.on()

    for _row in range(ICON_H):
        row_len = (ICON_RLE[pos] << 8) | ICON_RLE[pos + 1]
        pos += 2
        end = pos + row_len
        lx = 0

        while pos < end:
            run = ICON_RLE[pos]
            color = PALETTE[ICON_RLE[pos + 1]]
            pos += 2
            hi = color >> 8
            lo = color & 255
            stop = lx + run

            while lx < stop:
                off = lx * 2
                line[off] = hi
                line[off + 1] = lo
                lx += 1

        display.spi.write(line)

    display.cs.on()


def main():
    display = ILI9341()
    display.init()
    draw_bin_icon(display)
    print("Muelltonnen-Piktogramm auf Display gezeichnet")

    while True:
        sleep_ms(1000)


main()
